/**
 * @brief 解析一个 UTF-8 或 GBK 编码字符。
 * @param text 字符串当前位置。
 * @param code 返回 Unicode 编码或带标记的 GBK 编码。
 * @return 当前字符占用的字节数，字符串结束时返回 0。
 */
static uint8_t font_decode_text_impl(const uint8_t *text, uint32_t *code)
{
  uint8_t first;
  uint8_t second;
  uint8_t third = 0;
  uint8_t fourth;

  first = text[0];
  if (first == 0)
  {
    return 0;
  }
  if (first < 0x80)
  {
    *code = first;
    return 1;
  }

  second = text[1];
  if (first >= 0xC2 && first <= 0xDF &&
      second != 0 &&
      second >= 0x80 && second <= 0xBF)
  {
    *code = ((uint32_t)(first & 0x1F) << 6) | (second & 0x3F);
    return 2;
  }
  if (first >= 0xE0 && first <= 0xEF &&
      second != 0)
  {
    third = text[2];
  }
  else
  {
    third = 0;
  }
  if (first >= 0xE0 && first <= 0xEF &&
      second >= 0x80 && second <= 0xBF &&
      third != 0 &&
      third >= 0x80 && third <= 0xBF)
  {
    *code = ((uint32_t)(first & 0x0F) << 12) |
            ((uint32_t)(second & 0x3F) << 6) | (third & 0x3F);
    return 3;
  }
  if (first >= 0xF0 && first <= 0xF4)
  {
    fourth = 0;
    if (second != 0 && third != 0)
    {
      fourth = text[3];
    }
    if (second >= 0x80 && second <= 0xBF &&
        third >= 0x80 && third <= 0xBF &&
        fourth != 0 &&
        fourth >= 0x80 && fourth <= 0xBF)
    {
      *code = ((uint32_t)(first & 0x07) << 18) |
              ((uint32_t)(second & 0x3F) << 12) |
              ((uint32_t)(third & 0x3F) << 6) | (fourth & 0x3F);
      return 4;
    }
  }

  if (first >= 0x81 && first <= 0xFE &&
      second != 0 &&
      second >= 0x40 && second <= 0xFE && second != 0x7F)
  {
    *code = FONT_CODE_GBK_FLAG | ((uint32_t)first << 8) | second;
    return 2;
  }

  *code = first;
  return 1;
}

