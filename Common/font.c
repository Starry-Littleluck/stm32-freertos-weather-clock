/**
 * @brief 计算 GBK 字符在连续字库中的索引。
 * @param gbk GBK 双字节编码。
 * @return 字模索引，编码无效时返回 0xFFFF。
 */
static uint16_t Font_GbkIndex(uint16_t gbk)
{
  uint8_t high;
  uint8_t low;

  high = (uint8_t)(gbk >> 8);
  low = (uint8_t)gbk;
  if (high < 0x81 || high > 0xFE ||
      low < 0x40 || low > 0xFE || low == 0x7F)
  {
    return 0xFFFF;
  }
  if (low < 0x7F)
  {
    return (uint16_t)(high - 0x81) * 190 + low - 0x40;
  }
  return (uint16_t)(high - 0x81) * 190 + low - 0x41;
}

/**
 * @brief 从外部 Flash 读取指定中文字符的点阵。
 * @param code Unicode 编码或 Font_DecodeText 返回的 GBK 编码。
 * @param size 字体高度，支持 12、16、24。
 * @param glyph 点阵接收缓冲区。
 * @return 0 表示成功，1 表示没有对应字模。
 */
uint8_t Font_ReadGlyph(uint32_t code, uint8_t size, uint8_t *glyph)
{
  uint16_t gbk;
  uint16_t index;
  uint16_t glyph_size;
  uint32_t address;

  if (s_font_flash_ready == 0)
  {
    Font_Flash_Init();
  }

  if (FONT_CODE_IS_GBK(code))
  {
    gbk = FONT_CODE_GBK_VALUE(code);
  }
  else
  {
    gbk = Font_UnicodeToGbk(code);
  }
  index = Font_GbkIndex(gbk);
  if (index == 0xFFFF)
  {
    return 1;
  }

  if (size == 12)
  {
    address = FONT_FLASH_GBK12_ADDRESS;
    glyph_size = 24;
  }
  else if (size == 16)
  {
    address = FONT_FLASH_GBK16_ADDRESS;
    glyph_size = 32;
  }
  else if (size == 24)
  {
    address = FONT_FLASH_GBK24_ADDRESS;
    glyph_size = 72;
  }
  else
  {
    return 1;
  }

  return Font_Flash_Read(address + (uint32_t)index * glyph_size,
                         glyph, glyph_size);
}
