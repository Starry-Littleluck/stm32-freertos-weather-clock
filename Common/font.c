/**
 * @brief 获取 ASCII 字模及其宽度、每列字节数。
 * @param data ASCII 字符。
 * @param size 字体高度，支持 12、16、24、32。
 * @param width 返回字符宽度。
 * @param bytes 返回每列占用的字节数。
 * @return 字模地址，字号不支持时返回 0。
 */
static const uint8_t *font_get_ascii_glyph_impl(uint8_t data, uint8_t size,
                                                uint8_t *width, uint8_t *bytes)
{
  if (data < ' ' || data > '~' || width == 0 || bytes == 0)
  {
    return 0;
  }
  if (size == 12)
  {
    *width = 6;
    *bytes = 2;
    return asc2_1206[data - ' '];
  }
  if (size == 16)
  {
    *width = 8;
    *bytes = 2;
    return asc2_1608[data - ' '];
  }
  if (size == 24)
  {
    *width = 12;
    *bytes = 3;
    return asc2_2412[data - ' '];
  }
  if (size == 32)
  {
    *width = 16;
    *bytes = 4;
    return asc2_3216[data - ' '];
  }
  return 0;
}

/**
 * @brief 获取字符在屏幕上的显示宽度。
 * @param code Unicode、GBK 标记编码或 ASCII 编码。
 * @param size 字体高度。
 * @return ASCII 字符宽度为字号的一半，中文字符宽度等于字号。
 */
static uint8_t font_get_char_width_impl(uint32_t code, uint8_t size)
{
  return (code <= 0x7F) ? (uint8_t)(size / 2) : size;
}

