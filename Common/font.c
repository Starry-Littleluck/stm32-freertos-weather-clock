/**
 * @brief 按范围擦除字库所需的全部扇区。
 * @param address 起始地址。
 * @param length 数据长度。
 * @return 0 表示成功，其他值表示失败。
 */
uint8_t Font_Flash_EraseRange(uint32_t address, uint32_t length)
{
  uint32_t end_address;

  end_address = address + length;
  address &= ~(W25Q128_SECTOR_SIZE - 1);
  while (address < end_address)
  {
    if (Font_Flash_Erase(address) != 0)
    {
      return 1;
    }
    address += W25Q128_SECTOR_SIZE;
  }
  return 0;
}

/**
 * @brief 分段写入字库数据，兼容 W25Q128 的 16 位长度接口。
 * @param address Flash 起始地址。
 * @param data 待写入的数据。
 * @param length 数据长度。
 * @return 0 表示成功，其他值表示失败。
 */
uint8_t Font_Flash_Write(uint32_t address, const uint8_t *data, uint32_t length)
{
  uint16_t count;
  uint8_t status;

  while (length != 0)
  {
    count = (length > 65535) ? 65535 : (uint16_t)length;
    status = W25Q128_Write(address, data, count);
    if (status != 0)
    {
      return status;
    }
    address += count;
    data += count;
    length -= count;
  }
  return 0;
}

/**
 * @brief 分段读取字库数据，兼容 W25Q128 的 16 位长度接口。
 * @param address Flash 起始地址。
 * @param data 数据接收地址。
 * @param length 数据长度。
 * @return 0 表示成功，其他值表示失败。
 */
uint8_t Font_Flash_Read(uint32_t address, uint8_t *data, uint32_t length)
{
  uint16_t count;

  while (length != 0)
  {
    count = (length > 65535) ? 65535 : (uint16_t)length;
    if (W25Q128_Read(address, data, count) != 0)
    {
      return 1;
    }
    address += count;
    data += count;
    length -= count;
  }
  return 0;
}
